"""Generate the clock face bitmap fonts (python/ui/fonts/*.py) from DejaVu Sans TTFs.

Usage: python tools/make_fonts.py [--font-dir DIR]

DIR must contain DejaVuSans.ttf and DejaVuSans-Bold.ttf (DejaVu fonts license:
free to use and redistribute). By default the copy bundled with matplotlib is used.
Requires Pillow.

Generated module format (read by python/ui/writer.py):
    HEIGHT    glyph height in pixels (same for all glyphs)
    BASELINE  pixels from the glyph top to the baseline
    CHARS     the characters in the font
    WIDTHS    advance width of each char (bytes)
    DATA      glyph bitmaps, MONO_HLSB, ((width + 7) // 8) * HEIGHT bytes each, in CHARS order
"""

import argparse
import os

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(ROOT, "python", "ui", "fonts")

ASCII = "".join(chr(c) for c in range(32, 127))

# name: (ttf file, pixel size, characters)
FONTS = {
    "date": ("DejaVuSans-Bold.ttf", 13, ASCII),
    "small": ("DejaVuSans.ttf", 11, ASCII),
    "clock": ("DejaVuSans-Bold.ttf", 46, "0123456789:-"),
    "value": ("DejaVuSans-Bold.ttf", 26, "0123456789.-"),
    "unit": ("DejaVuSans-Bold.ttf", 15, "°C%"),
}


def default_font_dir():
    try:
        import matplotlib
    except ImportError:
        raise SystemExit("matplotlib not found: pass --font-dir with the DejaVu TTF files")
    return os.path.join(os.path.dirname(matplotlib.__file__), "mpl-data", "fonts", "ttf")


def render_font(ttf_path, size, chars):
    font = ImageFont.truetype(ttf_path, size)
    boxes = [font.getbbox(c, anchor="ls") for c in chars]
    top = min(b[1] for b in boxes)
    bottom = max(b[3] for b in boxes)
    height = bottom - top
    baseline = -top
    widths = bytearray()
    data = bytearray()
    for c in chars:
        width = max(1, round(font.getlength(c)))
        img = Image.new("1", (width, height), 0)
        draw = ImageDraw.Draw(img)
        draw.fontmode = "1"  # no anti-aliasing: crisp 1-bit glyphs
        draw.text((0, baseline), c, font=font, fill=1, anchor="ls")
        px = img.load()
        stride = (width + 7) // 8
        for y in range(height):
            row = bytearray(stride)
            for x in range(width):
                if px[x, y]:
                    row[x >> 3] |= 0x80 >> (x & 7)
            data += row
        widths.append(width)
    return height, baseline, bytes(widths), bytes(data)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--font-dir", default=None, help="directory with the DejaVu TTF files")
    args = parser.parse_args()
    font_dir = args.font_dir or default_font_dir()

    os.makedirs(OUT_DIR, exist_ok=True)
    with open(os.path.join(OUT_DIR, "__init__.py"), "w", newline="\n") as f:
        f.write("# Bitmap fonts generated by tools/make_fonts.py.\n")

    for name, (ttf, size, chars) in FONTS.items():
        height, baseline, widths, data = render_font(os.path.join(font_dir, ttf), size, chars)
        path = os.path.join(OUT_DIR, name + ".py")
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write("# Generated by tools/make_fonts.py from %s %dpx - do not edit.\n" % (ttf, size))
            f.write("HEIGHT = %d\n" % height)
            f.write("BASELINE = %d\n" % baseline)
            f.write("CHARS = %r\n" % chars)
            f.write("WIDTHS = %r\n" % widths)
            f.write("DATA = %r\n" % data)
        print("wrote %s (%d glyphs, height %d, %d bytes)" % (path, len(chars), height, len(data)))


if __name__ == "__main__":
    main()
