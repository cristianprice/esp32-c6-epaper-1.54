"""Generate python/ui/icons.py (MONO_HLSB bitmaps) from tools/icon_art.py.

Usage: python tools/make_icons.py
"""

import os

from icon_art import ICONS, SCALE

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "python", "ui", "icons.py")


def scaled(rows, factor):
    """Nearest-neighbour upscale, so the device never scales at runtime."""
    return ["".join(c * factor for c in row) for row in rows for _ in range(factor)]


def to_hlsb(rows):
    width = len(rows[0])
    assert width % 8 == 0, "icon width must be a multiple of 8"
    data = bytearray()
    for row in rows:
        assert len(row) == width, row
        for x in range(0, width, 8):
            byte = 0
            for bit, c in enumerate(row[x : x + 8]):
                if c == "#":
                    byte |= 0x80 >> bit
            data.append(byte)
    return width, len(rows), bytes(data)


def main():
    lines = [
        "# Generated by tools/make_icons.py from tools/icon_art.py - do not edit.",
        "# Each icon: (width, height, MONO_HLSB bytes); a set bit is a black pixel.",
        "",
    ]
    for name, rows in ICONS.items():
        w, h, data = to_hlsb(scaled(rows, SCALE.get(name, 1)))
        lines.append("%s = (%d, %d, %r)" % (name, w, h, data))
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
