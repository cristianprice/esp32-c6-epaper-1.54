"""Generate docs/clock_face_mockup.svg using the same icon pixel art as the firmware.

Usage: python tools/make_mockup.py
"""

import os

from icon_art import DROPLET, PLUMBER, THERMOMETER

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "docs", "clock_face_mockup.svg")


def pixel_path(rows, x0, y0, scale=1):
    """One SVG path of unit squares for every black pixel (row runs merged)."""
    parts = []
    for y, row in enumerate(rows):
        x = 0
        while x < len(row):
            if row[x] == "#":
                start = x
                while x < len(row) and row[x] == "#":
                    x += 1
                parts.append(
                    "M%d %dh%dv%dh-%dz"
                    % (x0 + start * scale, y0 + y * scale, (x - start) * scale, scale, (x - start) * scale)
                )
            else:
                x += 1
    return '<path d="%s"/>' % "".join(parts)


def battery(x, y, percent):
    fill_w = round(19 * percent / 100)
    return (
        '<rect x="%d.5" y="%d.5" width="24" height="11" fill="none" stroke="#000"/>'
        '<rect x="%d" y="%d" width="2" height="5"/>'
        '<rect x="%d" y="%d" width="%d" height="7"/>'
    ) % (x, y, x + 25, y + 3, x + 3, y + 3, fill_w)


SVG = """<?xml version="1.0" encoding="UTF-8"?>
<!--
  Generated by tools/make_mockup.py - do not edit by hand.
  Clock face mockup for the Waveshare ESP32-C6-ePaper-1.54 (200x200 px, 1-bit black/white).
  Coordinates are real panel pixels; the image is scaled 3x for viewing. Icons use the same
  pixel art as the firmware; fonts are stand-ins for the font_to_py bitmap fonts.
-->
<svg xmlns="http://www.w3.org/2000/svg" width="600" height="600" viewBox="0 0 200 200"
     font-family="DejaVu Sans, Verdana, Arial, sans-serif" fill="#000" shape-rendering="crispEdges">
  <rect x="0" y="0" width="200" height="200" fill="#fff"/>

  <!-- top bar: date + battery -->
  <text x="6" y="17" font-size="13" font-weight="bold">Thu 08 Oct 2026</text>
  {battery}
  <text x="194" y="32" font-size="10" text-anchor="end">78%</text>
  <rect x="4" y="37" width="192" height="2"/>

  <!-- plumber icon (16x16 art at 2x) + time -->
  {plumber}
  <text x="120" y="102" font-size="48" font-weight="bold" text-anchor="middle"
        letter-spacing="-2">14:32</text>
  <rect x="4" y="121" width="192" height="2"/>
  <rect x="99" y="128" width="2" height="66"/>

  <!-- temperature (left half) -->
  {thermo}
  <text x="30" y="143" font-size="11">Temp</text>
  <text x="50" y="183" font-size="28" font-weight="bold" text-anchor="middle">22.4<tspan font-size="16" dy="-10">°C</tspan></text>

  <!-- humidity (right half) -->
  {droplet}
  <text x="130" y="143" font-size="11">Humidity</text>
  <text x="150" y="183" font-size="28" font-weight="bold" text-anchor="middle">48<tspan font-size="16" dy="-10">%</tspan></text>
</svg>
"""


def main():
    svg = SVG.format(
        battery=battery(166, 5, 78),
        plumber=pixel_path(PLUMBER, 8, 72, scale=2),
        thermo=pixel_path(THERMOMETER, 10, 130),
        droplet=pixel_path(DROPLET, 110, 130),
    )
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(svg)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
